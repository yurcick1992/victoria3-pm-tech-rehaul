        $n++
        $name = "v3tb_dump_$n"
        # (phase names are appended below, one per emitted phase)

        # one-month trigger window: on_monthly_pulse fires on the 1st, so this is hit exactly once
        $p = $date.Split('.')
        $y = [int]$p[0]; $m = [int]$p[1]
