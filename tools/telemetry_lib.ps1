<#
  telemetry_lib.ps1 - the ONE place that generates testbed telemetry script.

  Dot-sourced by build.ps1. Every arm of an experiment - the vanilla control and any modded
  build - gets its instrumentation from here, which is what makes a control valid: if the arms
  could differ in what they log, the comparison would not be like-for-like.

  Everything emitted below uses data functions VERIFIED in-game against 1.13.9. Before adding a
  metric, read TESTBED_METRICS.md: one bad data function voids the WHOLE debug_log line it sits
  in (it is not printed at all), and several plausible-looking paths silently return an empty
  value rather than erroring.

  The telemetry SPEC is a small JSON object, so a future UI can author it:
    {
      "dump_dates": ["1840.1.1", "1860.1.1"],     # each must be the 1st of a month
      "tags":       ["GBR", "FRA"],               # markets to dump
      "metrics":    ["market_goods"]              # which metric blocks to emit
    }
#>

# NOTE: deliberately no Set-StrictMode here. This file is DOT-SOURCED into build.ps1, and
# Set-StrictMode applies to the CALLER's scope - switching it on broke the builder's own
# `-not $_.disabled` property tests. A library must not change its caller's strictness.

# ---------------------------------------------------------------- SCHEMA VERSION ----
# CONSECUTIVE, MONOTONIC. Bump by ONE whenever the emitted telemetry changes in a way that makes
# an older session non-comparable - a new metric, a changed line format, a dropped field. Never
# reuse or renumber: a finding cites the version it was measured under, and that citation has to
# keep meaning the same thing forever. Record every bump in the table in TESTBED_METRICS.md and
# tag the affected findings in FINDINGS.md.
#
#   v1  market goods (buy/sell/price only), generated by the HARNESS. No events, no
#       imports/exports/production. -> FINDINGS F1, F2 (sessions deleted).
#   v2  builder-owned generator; market goods gain imports/exports/production; one-off events
#       (DEFAULT, DIPPLAY, PEACE, CAPIT).
#   v3  + country_state: per-country GDP / foreign-owned GDP / GDP abroad / market; building
#       counts + levels by category; world GDP. Market line gains owner + member. Events gain
#       WARSTART and true BANKRUPTCY (modifier poll).  -> FINDINGS F3, F4, F5.
#       ⚠ v3 has NO war/civil-war state, so a country-level snapshot can be distorted without
#       any way to tell from the data.
#   v4  + STATE line per country per dump: at_war / civil_war / revolutionary / in_default.
#   v5  + TREASURY, per TRACKED country: TCASH (gold, principal, credit, balance, investment pool,
#       unrealized taxes, weekly expenses), TREV (8 revenue lines), TEXP (17 expense lines) - the
#       in-game budget panel - and TRADE (country trade capacity + trade-centre count/levels).
#   v6  + POP line per country per dump (metric `population`): total workforce, peasant workforce,
#       slave workforce, dependents, mean state unemployment rate, total population. Rides inside
#       the existing every_country pass. UNVALIDATED until probed in-game.
#   v7  PHASED dumps (one logical dump emitted over 3 consecutive months, cutting the per-tick
#       log burst to ~1/3) + tag-scoping removed: treasury per EVERY country, market goods per
#       EVERY market. Country sets can differ slightly between phases - join on name.
#   v8  + ORIGINS: who supplied whom, per good, per importer market. Exporters pinned by
#       `every_market = { limit = { owner = c:X } }` - a scope-path argument voids. Own phase (p3).
#   v9  + URBAN CENTRE counts/levels per country (verified is_building_type mechanism), and the
#       `scenario_probe` metric: the unverified half of the scenario-calibration instrument -
#       per-building enumeration (type/level/employment), pop standard-of-living by stratum, and
#       the three candidate EARLY-READ hooks (game start, a day-7 scheduled event, a 1836.1.1
#       monthly pulse). Adds an events/ file, the first the builder has ever emitted.
#   v10 + WAGES (metric `wages`, TESTBED_METRICS §5): WC per country + SW per state of every tracked
#       market + PW per POP of the deep markets. State average annual wage, pop income split into
#       workforce/dependent, and the measured workforce ratio. Deep markets are the LEAD COUNTRY AND
#       ITS SUBJECTS, not the whole market - see Get-WageBlock for why. New script values
#       v3tb_popobj_count (graduated from the probe file), v3tb_state_count, v3tb_poptype_id.
$script:TELEMETRY_VERSION = 13

function Get-TelemetryVersion { return $script:TELEMETRY_VERSION }

function Get-TelemetryDefaults {
    return [ordered]@{
        dump_dates = @("1840.1.1")
        tags       = @("GBR", "FRA")
        metrics    = @("market_goods")
        origin_goods = @()
        breakdown_dates = @()      # sparse dates for `breakdown_sparse` (the pop/non-pop channel split)
        breakdown_tags  = @()      # markets for it, ONE PER TICK - two in one tick truncates the ring
        wide_dates      = @()      # dates for `market_goods_wide` (order book only, long tag list)
        wide_tags       = @()      # the "plausibly advanced" countries worth a yearly world check
    }
}

function Read-TelemetrySpec {
    param([string]$Path)
    $spec = Get-TelemetryDefaults
    if ($Path) {
        if (-not (Test-Path $Path)) { throw "telemetry spec not found: $Path" }
        $j = Get-Content $Path -Raw -Encoding UTF8 | ConvertFrom-Json
        foreach ($k in @("dump_dates", "tags", "metrics", "origin_goods",
                         "breakdown_dates", "breakdown_tags", "wide_dates", "wide_tags")) {
            if ($j.PSObject.Properties.Name -contains $k -and $j.$k) { $spec[$k] = @($j.$k) }
        }
        # An OBJECT, not an array (group -> successor chain), so it cannot go through the @() loop
        # above - that would flatten it to a list of property bags and lose the group names.
        if ($j.PSObject.Properties.Name -contains 'wage_pop_markets' -and $j.wage_pop_markets) {
            $spec['wage_pop_markets'] = $j.wage_pop_markets
        }
    }
    foreach ($d in $spec.dump_dates) {
        if ($d -notmatch '^\d{3,4}\.\d{1,2}\.1$') {
            throw "telemetry dump date '$d' must be the 1st of a month - on_monthly_pulse only fires then"
        }
    }
    return $spec
}

function New-TelemetryScriptValues {
    <#
      Returns the text of common/script_values/zzz_v3tb_values.txt - the iterating script values
      the telemetry reads with .MakeScope.ScriptValue('name'). Mechanism 2 in TESTBED_METRICS.md:
      this is the ONLY way to get an aggregate (a per-category building count) into one log line.

      Building categories follow the vanilla building_group HIERARCHY (common/building_groups):
      is_building_group matches PARENT groups, so bg_manufacturing covers light/heavy/military
      industry and ship construction in one test. Categories are the user's four, with the
      auto-scaling groups split out so they can be included or ignored at analysis time:
        mfg     = bg_manufacturing
        extract = bg_mining + bg_logging + bg_rubber + bg_oil_extraction   (gold fields separate)
        agri    = bg_agriculture + bg_ranching + bg_plantations + bg_fishing + bg_whaling
                  (bg_subsistence_* are children of agriculture/ranching -> counted separately
                   and subtracted at analysis time)
        subsist = bg_subsistence_agriculture + bg_subsistence_ranching
        gold    = bg_gold_fields
      "non-economic" is DERIVED in analysis as total - (mfg + extract + agri), so a group we
      forgot cannot silently vanish from the accounting.
    #>
    $cats = [ordered]@{
        mfg     = @('bg_manufacturing')
        extract = @('bg_mining','bg_logging','bg_rubber','bg_oil_extraction')
        agri    = @('bg_agriculture','bg_ranching','bg_plantations','bg_fishing','bg_whaling')
        subsist = @('bg_subsistence_agriculture','bg_subsistence_ranching')
        gold    = @('bg_gold_fields')
    }
    $sv = @"
# AUTO-GENERATED by tools/telemetry_lib.ps1 via build.ps1 - do not edit by hand.
# Iterating script values for testbed building counts (TESTBED_METRICS.md mechanism 2).

v3tb_bld_total = { value = 0
	every_scope_state = { every_scope_building = { add = 1 } } }
v3tb_lvl_total = { value = 0
	every_scope_state = { every_scope_building = { add = level } } }
"@
    foreach ($c in $cats.Keys) {
        $lim = if ($cats[$c].Count -eq 1) {
            "is_building_group = $($cats[$c][0])"
        } else {
            "OR = { " + (($cats[$c] | ForEach-Object { "is_building_group = $_" }) -join ' ') + " }"
        }
        $sv += @"


v3tb_bld_$c = { value = 0
	every_scope_state = { every_scope_building = {
		limit = { $lim }
		add = 1 } } }
v3tb_lvl_$c = { value = 0
	every_scope_state = { every_scope_building = {
		limit = { $lim }
		add = level } } }
"@
    }
    $sv += @"


# World GDP - summed over every country, read from any country scope.
v3tb_world_gdp = { value = 0
	every_country = { add = gdp } }

# Country STATE flags (0/1). A country at war - and above all one in a civil war - can have its
# economy distorted by orders of magnitude, so a snapshot is not interpretable without knowing
# which state the country was in when it was taken. Civil war is reported separately from and in
# addition to regular war (a civil war also sets is_at_war).
v3tb_at_war = { value = 0
	if = { limit = { is_at_war = yes } value = 1 } }
v3tb_civil_war = { value = 0
	if = { limit = { is_in_civil_war = yes } value = 1 } }
v3tb_revolutionary = { value = 0
	if = { limit = { is_revolutionary = yes } value = 1 } }
v3tb_in_default = { value = 0
	if = { limit = { in_default = yes } value = 1 } }

# Per-POP values, read via MakeScope.ScriptValue on the pop scope. Belt-and-braces beside the data
# functions: `standard_of_living` is verified as a pop-scope script-value KEYWORD (it is what the
# per-stratum SoL sums use), whereas Pop.GetFormattedStandardOfLiving is a GUI accessor that may
# return decorated text. Whichever survives, one of them gives the real distribution.
v3tb_pop_sol = { value = 0
	add = standard_of_living }
v3tb_pop_wf = { value = 0
	add = workforce }

# POP-OBJECT COUNT per country. Not a population figure - a count of pop OBJECTS, which is exactly
# the number of log lines a per-pop sweep of that country will emit. That makes it the sizing
# instrument for any per-pop metric: one line that cannot be truncated, versus counting the
# thousands of lines whose truncation is the very thing being guarded against.
# (Graduated from zzz_v3tb_probe_values.txt, and REMOVED there - two files defining one script-value
#  key is a silent override, and the probe file is only emitted when a probe metric asks for it.)
v3tb_popobj_count = { value = 0
	every_scope_state = { every_scope_pop = { add = 1 } } }
v3tb_state_count = { value = 0
	every_scope_state = { add = 1 } }

# ---- CONSTRUCTION QUEUE (v13 probe): country-scope comparator triggers found in the exe pool
# (construction_queue_num_queued_levels + _government_/_private_). UNVERIFIED whether a script
# value can read them as value fields - THE L6 HAZARD: if not, these read 0 silently. The probe
# design therefore logs them beside a canary every reader must check: at any date past 1836.2,
# a great power ALWAYS has something queued, so an all-zero CQ line on GBR means the wrap failed,
# not that the queue is empty.
v3tb_queue_all = { value = construction_queue_num_queued_levels }
v3tb_queue_gov = { value = construction_queue_num_queued_government_levels }
v3tb_queue_priv = { value = construction_queue_num_queued_private_levels }

# ---- POPULATION / WORKFORCE ----
# The capital-scarcity measure: how much of a country's workforce is in subsistence (peasants) or
# idle, versus gainfully employed. Vanilla late-game advanced economies run peasants and unemployed
# to ~0, which the mod is meant to prevent by making modernisation cost capital.
#
# `workforce` and `dependents` are pop-scope numeric triggers (common/trigger_localization), so they
# work as script-value keywords under every_scope_pop. `is_pop_type` is the vanilla filter idiom.
v3tb_wf_total = { value = 0
	every_scope_state = { every_scope_pop = { add = workforce } } }
v3tb_wf_peasants = { value = 0
	every_scope_state = { every_scope_pop = {
		limit = { is_pop_type = peasants }
		add = workforce } } }
v3tb_wf_slaves = { value = 0
	every_scope_state = { every_scope_pop = {
		limit = { is_pop_type = slaves }
		add = workforce } } }
v3tb_dependents = { value = 0
	every_scope_state = { every_scope_pop = { add = dependents } } }

# Unemployment. There is NO unemployed-count keyword; `state_unemployment_rate` (state scope) is
# the only handle, so this reproduces VANILLA'S OWN estimate from common/script_values/je_values.txt
# (mon_unemployment_estimate): the unweighted mean rate across states. Vanilla's comment there says
# the trigger "is way off actual unemployment rate" and doubles it - we do NOT double, and report
# the raw mean. Treat it as directional, not a count. An actual count would need
# State.GetNumUnemployedWorkingAdults, which is a data function and cannot be summed in a script value.
v3tb_unemp_rate = { value = 0
	every_scope_state = { add = state_unemployment_rate }
	if = { limit = { num_states > 0 } divide = num_states } }

# Trade centres. `level` is the only building-scope numeric keyword confirmed working, so levels
# and count are the reliable measures; staffing is probed separately (see New-TelemetryProbeValues).
v3tb_bld_tradecenter = { value = 0
	every_scope_state = { every_scope_building = {
		limit = { is_building_type = building_trade_center }
		add = 1 } } }
v3tb_lvl_tradecenter = { value = 0
	every_scope_state = { every_scope_building = {
		limit = { is_building_type = building_trade_center }
		add = level } } }

# ---- URBAN CENTRES ----
# The scenario panel cannot model these: the game raises them itself from state urbanization by an
# engine-side rule that is NOT in the game files (common/building_groups gives urbanization per
# building LEVEL, but not the divisor). So the level count has to be MEASURED. This uses the same
# verified is_building_type mechanism as the trade-centre counts, and is therefore the guaranteed
# floor under the richer per-building enumeration probed by `scenario_probe`.
# ---- STANDARD OF LIVING BY STRATUM ----
# The scenario panel otherwise gives every market the same per-class wealth level (35/16/9), which
# cannot be right for Britain and the Qing at once. VERIFIED 2026-08-02 (session 20260802_110757):
# `standard_of_living` resolves as a pop-scope script-value keyword, and the nested value block
# below works - GBR's people-weighted mean came to 10.13 against GetAverageSoLByPopulation's 10.23,
# an independent cross-check. So these live in the PRODUCTION values file, not the probe one.
# ⚠ `wealth` at pop scope returns the SAME number as `standard_of_living`; they are one quantity.
#
# The strata are the SAME buckets extract_presets.ps1 uses ($STRATA) - the fitted consumption
# distribution is keyed by them, so a different bucketing here would silently mis-key it.
# Denominators are `v3tb_swf_*`, deliberately NOT `v3tb_wf_*`: those already exist above, and two
# definitions of one script-value key is a silent override.
#
# STRATUM_VALUES_MARKER (the per-stratum pairs are appended here by the generator)

v3tb_bld_urban_center = { value = 0
	every_scope_state = { every_scope_building = {
		limit = { is_building_type = building_urban_center }
		add = 1 } } }
v3tb_lvl_urban_center = { value = 0
	every_scope_state = { every_scope_building = {
		limit = { is_building_type = building_urban_center }
		add = level } } }
"@
    $sv = $sv -replace '# STRATUM_VALUES_MARKER.*', (Get-StratumSolValues)
    $sv += "`r`n`r`n# Pop TYPE as an integer - see Get-WagePopTypes for why the name is not used.`r`n"
    $sv += (Get-WagePopTypeValue)
    return $sv
}

function Get-StratumSolValues {
    <#
      People-weighted SoL and workforce per stratum, as script-value text. Shared by the production
      values file (where these belong, now that they are verified) - see the marker it replaces.
    #>
    $strata = [ordered]@{
        upper    = @('aristocrats','capitalists')
        middle   = @('clerks','shopkeepers','engineers','bureaucrats','academics','clergymen','officers')
        lower    = @('laborers','farmers','machinists','soldiers')
        peasants = @('peasants')
        slaves   = @('slaves')
    }
    $out = @()
    foreach ($s in $strata.Keys) {
        $lim = if ($strata[$s].Count -eq 1) {
            "is_pop_type = $($strata[$s][0])"
        } else {
            "OR = { " + (($strata[$s] | ForEach-Object { "is_pop_type = $_" }) -join ' ') + " }"
        }
        $out += @"
v3tb_solw_$s = { value = 0
	every_scope_state = { every_scope_pop = {
		limit = { $lim }
		add = { value = standard_of_living  multiply = workforce } } } }
v3tb_swf_$s = { value = 0
	every_scope_state = { every_scope_pop = {
		limit = { $lim }
		add = workforce } } }
"@
    }
    return ($out -join "`r`n")
}

