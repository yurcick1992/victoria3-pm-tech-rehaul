        # Every function below was verified in-game 2026-07-31 (probe sessions 20260731_232310 and
        # _232749): all 9 cash + 8 revenue + 17 expense functions returned values, zero data errors.
        # Bundled into four lines rather than one-per-line because they are proven; the field order
        # here IS the parsing contract, so append new fields at the END of a line, never insert.
        # Tracked tags only - this is per-country detail, not an every_country sweep.
        if ($metrics -contains "treasury") {
            $cashF = @('GetGoldReserves','GetPrincipal','GetMaxCredit','GetRemainingCredit',
                       'GetWeeklyBalance','GetInvestmentPool','GetInvestmentPoolChange',
                       'GetUnrealizedTaxes','GetWeeklyExpenses')
            $revF  = @('GetIncomeTaxIncome','GetPollTaxIncome','PredictConsumptionTaxes',
                       'PredictTariffs','PredictMinting','PredictDiplomaticPactsIncome',
                       'PredictTreatyIncome','GetInvestmentIncome')
