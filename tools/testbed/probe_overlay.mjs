#!/usr/bin/env node
// tools/testbed/probe_overlay.mjs — the content of the ENGINE-PROBE overlay arms (2026-11-20, the pre-1.2 probes 2-4).
//
// An overlay arm is vanilla + telemetry + ONE declared change (TESTBED_OPERATIONS §2.2). build.ps1 -Overlay calls this for a config
// that carries `probe_overlay: { kind, ... }`, and then refuses any file outside the part's declared paths. Three kinds:
//
//   tech_ai_weights   probe 4 (BALANCE_FRAMEWORK §10.119 item 3): vanilla's three technology files, with `multiply = <m>` appended
//                     as the last line of the ai_weight block of each technology the config names. Either an explicit map
//                     `multipliers: { <tech>: <m> }`, or `design: { eras: [1,2], mults: [...], rotate: k }`: every technology of
//                     those tech eras, sorted by tree, era and key, is dealt round-robin into len(mults) groups, and group g takes
//                     mults[(g + rotate) % len]. Two configs that differ only in `rotate` swap the groups' multipliers, so a
//                     technology's own pull cancels between them. `--print-design` prints the group table (JSON) and writes nothing, for the reader.
//   global_tech_gate  probe 2 (§10.115 ruling 7): in a vanilla production-method file, each named method's
//                     `unlocking_technologies = {` becomes `unlocking_global_technologies = {` (exactly once per method, or throw).
//   resource_hooks    probe 3 (§10.115: gold's depleted fields, oil's linked discovery): a script that forces discoveries,
//                     depletions and potential changes on fixed dates and logs what the hooks and the slot counts do
//                     (`PROBE_RH|...` lines in debug.log); one state-region file with `discover_chance_mult = 0` on one block.
//
// Usage: node tools/testbed/probe_overlay.mjs --config <cfg.json> --mod <modDir> --game <gameDir>
// Prints one line per written file (relative path). Throws on anything it cannot do exactly.
import fs from 'fs';
import path from 'path';

const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : undefined; };
const cfgPath = arg('--config'), modDir = arg('--mod'), gameDir = arg('--game');
if (!cfgPath || !modDir || !gameDir) throw new Error('usage: --config <cfg> --mod <modDir> --game <gameDir>');
const cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8').replace(/^﻿/, ''));
const po = cfg.probe_overlay;
if (!po || !po.kind) throw new Error(`${cfgPath}: no probe_overlay.kind`);
const G = fs.existsSync(path.join(gameDir, 'game')) ? path.join(gameDir, 'game') : gameDir;
const BOM = '﻿';
const readV = (rel) => fs.readFileSync(path.join(G, rel), 'utf8').replace(/^﻿/, '');
const written = [];
const put = (rel, text) => {
  const p = path.join(modDir, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, BOM + text.replace(/^﻿/, ''));
  written.push(rel.replace(/\\/g, '/'));
};
const header = (what) => `# AUTO-GENERATED by tools/testbed/probe_overlay.mjs (${po.kind}) from ${path.basename(cfgPath)} - an ENGINE PROBE overlay, never a control, never economy data of a book.\n# ${what}\n`;

// the block of `<key> = {` that starts a line at column 0, as [start, end) offsets (end after the closing brace)
function topBlock(text, key) {
  const re = new RegExp(`^${key}\\s*=\\s*\\{`, 'm');
  const m = re.exec(text);
  if (!m) return null;
  let depth = 0, i = m.index + m[0].length - 1;
  for (; i < text.length; i++) {
    const c = text[i];
    if (c === '#') { while (i < text.length && text[i] !== '\n') i++; continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return [m.index, i + 1]; }
  }
  throw new Error(`unbalanced block ${key}`);
}
// a nested `<key> = {` inside [a, b): its [start, end)
function innerBlock(text, a, b, key) {
  const re = new RegExp(`\\b${key}\\s*=\\s*\\{`, 'g');
  re.lastIndex = a;
  const m = re.exec(text);
  if (!m || m.index >= b) return null;
  let depth = 0, i = m.index + m[0].length - 1;
  for (; i < b; i++) {
    const c = text[i];
    if (c === '#') { while (i < b && text[i] !== '\n') i++; continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return [m.index, i + 1]; }
  }
  throw new Error(`unbalanced inner block ${key}`);
}

if (po.kind === 'tech_ai_weights') {
  const files = { production: 'common/technology/technologies/10_production.txt', military: 'common/technology/technologies/20_military.txt', society: 'common/technology/technologies/30_society.txt' };
  const texts = {}; const techs = [];
  for (const [tree, rel] of Object.entries(files)) {
    texts[tree] = readV(rel);
    for (const m of texts[tree].matchAll(/^([a-z0-9_]+)\s*=\s*\{/gm)) {
      const [a, b] = topBlock(texts[tree].slice(m.index), m[1]).map((x) => x + m.index);
      const body = texts[tree].slice(a, b);
      const era = +((body.match(/\bera\s*=\s*era_(\d)/) || [])[1] || 0);
      const hasW = /\bai_weight\s*=\s*\{/.test(body);
      techs.push({ key: m[1], tree, era, hasW });
    }
  }
  let mult = {};
  if (po.multipliers) mult = { ...po.multipliers };
  if (po.design) {
    const { eras, mults, rotate = 0 } = po.design;
    const pool = techs.filter((t) => eras.includes(t.era) && t.hasW).sort((x, y) => (x.tree + x.era + x.key).localeCompare(y.tree + y.era + y.key));
    let g = 0, last = '';
    const table = [];
    for (const t of pool) {
      const cell = t.tree + t.era;
      if (cell !== last) { last = cell; } // keep dealing across cells so every group spans every tree and era
      const grp = g % mults.length; g++;
      const m = mults[(grp + rotate) % mults.length];
      table.push({ tech: t.key, tree: t.tree, era: t.era, group: grp, mult: m });
      if (m !== 1) mult[t.key] = m;
    }
    if (process.argv.includes('--print-design')) { console.log(JSON.stringify({ config: path.basename(cfgPath), design: po.design, table }, null, 1)); process.exit(0); }
  }
  const byTree = {};
  for (const [key, m] of Object.entries(mult)) {
    const t = techs.find((x) => x.key === key);
    if (!t) throw new Error(`tech_ai_weights: no vanilla technology '${key}'`);
    if (!t.hasW) throw new Error(`tech_ai_weights: '${key}' has no ai_weight block`);
    if (!(m > 0)) throw new Error(`tech_ai_weights: multiplier for '${key}' must be > 0 (got ${m})`);
    (byTree[t.tree] ||= []).push([key, m]);
  }
  for (const [tree, list] of Object.entries(byTree)) {
    let text = texts[tree];
    // apply from the end so offsets stay valid
    const edits = list.map(([key, m]) => {
      const [a, b] = topBlock(text, key);
      const w = innerBlock(text, a, b, 'ai_weight');
      if (!w) throw new Error(`no ai_weight in ${key}`);
      return { key, m, at: w[1] - 1 };
    }).sort((x, y) => y.at - x.at);
    for (const e of edits) text = text.slice(0, e.at) + `\tmultiply = ${e.m} # PROBE OVERLAY tech_ai_weights\n\t` + text.slice(e.at);
    const check = (text.match(/# PROBE OVERLAY tech_ai_weights/g) || []).length;
    if (check !== list.length) throw new Error(`tech_ai_weights: ${tree} expected ${list.length} edits, found ${check}`);
    put(files[tree], header(`${list.length} technologies' ai_weight multiplied: ${list.map(([k, m]) => `${k}×${m}`).join(' ')}`) + text);
  }
  process.stderr.write(`tech_ai_weights: ${Object.keys(mult).length} technologies changed over ${Object.keys(byTree).length} file(s)\n`);
} else if (po.kind === 'global_tech_gate') {
  const byFile = {};
  for (const [pm, spec] of Object.entries(po.methods || {})) (byFile[spec.file] ||= []).push([pm, spec]);
  if (!Object.keys(byFile).length) throw new Error('global_tech_gate: no methods');
  for (const [file, list] of Object.entries(byFile)) {
    const rel = `common/production_methods/${file}`;
    let text = readV(rel);
    for (const [pm, spec] of list) {
      const [a, b] = topBlock(text, pm) || (() => { throw new Error(`no method ${pm} in ${rel}`); })();
      const body = text.slice(a, b);
      const n = (body.match(/\bunlocking_technologies\s*=\s*\{/g) || []).length;
      if (n !== 1) throw new Error(`${pm}: ${n} unlocking_technologies blocks, expected exactly 1`);
      if (spec.tech && !new RegExp(`unlocking_technologies\\s*=\\s*\\{[^}]*\\b${spec.tech}\\b`).test(body)) throw new Error(`${pm}: its unlocking_technologies does not name ${spec.tech}`);
      const nb = body.replace(/\bunlocking_technologies(\s*=\s*\{)/, 'unlocking_global_technologies$1 # PROBE OVERLAY global_tech_gate (was unlocking_technologies)');
      text = text.slice(0, a) + nb + text.slice(b);
    }
    put(rel, header(`methods gated on the WORLD's technology: ${list.map(([p]) => p).join(' ')}`) + text);
  }
} else if (po.kind === 'resource_hooks') {
  // ---- the one state-region edit: discover_chance_mult = 0 on one gold-field block
  const z = po.zero_chance; // { file, state }
  const srel = `map_data/state_regions/${z.file}`;
  let st = readV(srel);
  const [a, b] = topBlock(st, z.state) || (() => { throw new Error(`no ${z.state} in ${srel}`); })();
  let body = st.slice(a, b);
  const rb = /resource\s*=\s*\{[^{}]*type\s*=\s*"building_gold_field"[^{}]*\}/.exec(body);
  if (!rb) throw new Error(`${z.state}: no gold-field resource block`);
  if (/discover_chance_mult/.test(rb[0])) throw new Error(`${z.state}: gold block already has discover_chance_mult`);
  const nblk = rb[0].replace(/\}$/, '\tdiscover_chance_mult = 0 # PROBE OVERLAY resource_hooks\n\t}');
  body = body.slice(0, rb.index) + nblk + body.slice(rb.index + rb[0].length);
  st = st.slice(0, a) + body + st.slice(b);
  put(srel, st); // map data: no comment header at the top, the file is vanilla's but for the one line

  // ---- script values: slot counts by the vanilla-proven trigger form ("num_potential_resources(bt:X)" > n), and the direct form
  const TYPES = ['building_gold_field', 'building_gold_mine', 'building_oil_rig', 'building_coal_mine', 'building_lead_mine', 'building_iron_mine'];
  const short = (t) => t.replace('building_', '');
  let sv = header('slot counts of a state, two forms: probe_rh_<type> counts by comparison (0-80), probe_rh_<type>_direct takes the value directly');
  for (const t of TYPES) {
    sv += `probe_rh_${short(t)} = {\n\tvalue = 0\n`;
    for (let n = 0; n < 80; n++) sv += `\tif = { limit = { "num_potential_resources(bt:${t})" > ${n} } add = 1 }\n`;
    sv += `}\n`;
    sv += `probe_rh_${short(t)}_direct = {\n\tvalue = "num_potential_resources(bt:${t})"\n}\n`;
  }
  put('common/script_values/zzz_probe_resource_values.txt', sv);

  const caps = (S) => TYPES.map((t) => `${short(t)}=[${S}.MakeScope.ScriptValue('probe_rh_${short(t)}')]/[${S}.MakeScope.ScriptValue('probe_rh_${short(t)}_direct')]`).join('|');
  const id = (S) => `[${S}.GetNameNoFormatting]|[${S}.GetOwner.GetNameNoFormatting]`;
  const date = '[TimeKeeper.GetCurrentDate.GetString]';
  const L = (tag, S, extra = '') => `debug_log = "PROBE_RH|${tag}|${date}|${id(S)}|${caps(S)}${extra}"`;
  // the steps, each on the first of a month (on_monthly_pulse, global; it does not fire on 1836.1.1)
  const oa = `${header('the resource-hook probe: hooks logged, effects forced on fixed months, slot counts logged before and after')}
on_resource_discovered = { on_actions = { probe_rh_on_discovered } }
on_resource_depleted = { on_actions = { probe_rh_on_depleted } }
on_monthly_pulse = { on_actions = { probe_rh_driver } }

# Root = State. Logs every firing with the slot counts as the hook sees them; on a state the probe tracks, the first firing
# forces a second discovery of the same type FROM INSIDE THE HOOK (does it re-fire the hook? does it reveal more?), at most twice.
probe_rh_on_discovered = {
	effect = {
		${L('HOOK_DISCOVERED', 'ROOT.GetState', "|tracked=[ROOT.GetState.MakeScope.Var('probe_rh_tracked').GetValue|0]|reentry=[ROOT.GetState.MakeScope.Var('probe_rh_reentry').GetValue|0]")}
		if = {
			limit = { has_variable = probe_rh_tracked NOT = { has_variable = probe_rh_reentry_done } }
			if = { limit = { NOT = { has_variable = probe_rh_reentry } } set_variable = { name = probe_rh_reentry value = 0 } }
			change_variable = { name = probe_rh_reentry add = 1 }
			if = {
				limit = { var:probe_rh_reentry >= 2 }
				set_variable = probe_rh_reentry_done
			}
			debug_log = "PROBE_RH|HOOK_FORCE_AGAIN|${date}|[ROOT.GetState.GetNameNoFormatting]|reentry=[ROOT.GetState.MakeScope.Var('probe_rh_reentry').GetValue|0]"
			force_resource_discovery = building_gold_field
			${L('HOOK_AFTER_FORCE', 'ROOT.GetState')}
		}
	}
}
probe_rh_on_depleted = {
	effect = {
		${L('HOOK_DEPLETED', 'ROOT.GetState')}
	}
}

probe_rh_driver = {
	effect = {
		# 1836.2.1 - the before picture, and forced discovery of gold fields in every tracked state (the zero-chance state included)
		if = {
			limit = { NOT = { has_global_variable = probe_rh_step1 } }
			set_global_variable = probe_rh_step1
			debug_log = "PROBE_RH|STEP1|${date}|force_resource_discovery = building_gold_field in every state with a gold-field potential"
			every_state = {
				limit = { has_potential_resource = building_gold_field }
				set_variable = { name = probe_rh_tracked value = 1 }
				${L('BEFORE_DISCOVERY', 'THIS.GetState')}
				force_resource_discovery = building_gold_field
				${L('AFTER_DISCOVERY', 'THIS.GetState', "|reentry=[THIS.GetState.MakeScope.Var('probe_rh_reentry').GetValue|0]")}
			}
		}
		else_if = {
			# 1836.3.1 - the month after: counts settle? vanilla's gold rush fired? a second plain force
			limit = { NOT = { has_global_variable = probe_rh_step2 } }
			set_global_variable = probe_rh_step2
			every_state = {
				limit = { has_variable = probe_rh_tracked }
				${L('MONTH_AFTER', 'THIS.GetState', "|rush_state=[THIS.GetState.MakeScope.Var('gold_rush_state').GetValue|0]")}
				if = { limit = { has_variable = gold_rush_state } debug_log = "PROBE_RH|VANILLA_GOLDRUSH_STATE|${date}|[THIS.GetState.GetNameNoFormatting]" }
				force_resource_discovery = building_gold_field
				${L('AFTER_SECOND_FORCE', 'THIS.GetState')}
			}
		}
		else_if = {
			# 1836.4.1 - forced depletion of gold fields: does the hook fire, where do the slots go (depleted_type = building_gold_mine)?
			limit = { NOT = { has_global_variable = probe_rh_step3 } }
			set_global_variable = probe_rh_step3
			every_state = {
				limit = { has_variable = probe_rh_tracked }
				${L('BEFORE_DEPLETION', 'THIS.GetState')}
				force_resource_depletion = building_gold_field
				${L('AFTER_DEPLETION', 'THIS.GetState')}
			}
		}
		else_if = {
			# 1836.5.1 - change_resource_potential (+3 gold mines; +2 oil where oil exists; +2 coal everywhere tracked) and
			# add_resource_potential = building_lead_mine; logged before and after
			limit = { NOT = { has_global_variable = probe_rh_step4 } }
			set_global_variable = probe_rh_step4
			every_state = {
				limit = { has_variable = probe_rh_tracked }
				${L('BEFORE_CHANGE', 'THIS.GetState')}
				state_region = {
					change_resource_potential = { type = building_gold_mine amount = 3 }
					change_resource_potential = { type = building_coal_mine amount = 2 }
				}
				if = {
					limit = { has_potential_resource = building_oil_rig }
					state_region = { change_resource_potential = { type = building_oil_rig amount = 2 } }
				}
				if = {
					limit = { NOT = { has_potential_resource = building_lead_mine } }
					state_region = { add_resource_potential = building_lead_mine }
					debug_log = "PROBE_RH|ADD_LEAD|${date}|[THIS.GetState.GetNameNoFormatting]"
				}
				${L('AFTER_CHANGE', 'THIS.GetState')}
			}
		}
		else_if = {
			# 1836.6.1 - negative change (gold mines -1), then the final picture
			limit = { NOT = { has_global_variable = probe_rh_step5 } }
			set_global_variable = probe_rh_step5
			every_state = {
				limit = { has_variable = probe_rh_tracked }
				${L('BEFORE_NEGATIVE', 'THIS.GetState')}
				state_region = { change_resource_potential = { type = building_gold_mine amount = -1 } }
				${L('AFTER_NEGATIVE', 'THIS.GetState')}
			}
		}
		else_if = {
			limit = { NOT = { has_global_variable = probe_rh_step6 } }
			set_global_variable = probe_rh_step6
			every_state = {
				limit = { has_variable = probe_rh_tracked }
				${L('FINAL', 'THIS.GetState')}
			}
		}
	}
}
`;
  put('common/on_actions/zzz_probe_resource_hooks.txt', oa);
} else {
  throw new Error(`unknown probe_overlay.kind '${po.kind}' (tech_ai_weights | global_tech_gate | resource_hooks)`);
}
for (const w of written) console.log(w);
